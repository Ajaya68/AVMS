CREATE TABLE AV_USER (
    USER_ID               NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID       NUMBER(19)  NOT NULL,
    EMPLOYEE_ID           NUMBER(19),
    USERNAME              VARCHAR2(40)  NOT NULL,
    EMAIL                 VARCHAR2(120) NOT NULL,
    MOBILE                VARCHAR2(30),
    PASSWORD_HASH         VARCHAR2(255) NOT NULL,
    FIRST_NAME            VARCHAR2(80),
    LAST_NAME             VARCHAR2(80),
    STATUS                VARCHAR2(20)  NOT NULL,
    FAILED_LOGIN_COUNT    NUMBER(5)     DEFAULT 0 NOT NULL,
    LOCKED_UNTIL          TIMESTAMP(6),
    LAST_LOGIN_AT         TIMESTAMP(6),
    PASSWORD_CHANGED_AT   TIMESTAMP(6),
    CREATED_AT            TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT            TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    VERSION_NO            NUMBER(19)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AV_USER PRIMARY KEY (USER_ID),
    CONSTRAINT FK_AV_USER_ORG FOREIGN KEY (ORGANIZATION_ID)
        REFERENCES AV_ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT UK_AV_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_AV_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_AV_USER_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED','LOCKED')),
    CONSTRAINT CK_AV_USER_FAILED CHECK (FAILED_LOGIN_COUNT >= 0)
);

CREATE TABLE AV_ROLE (
    ROLE_ID           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID   NUMBER(19),
    ROLE_CODE         VARCHAR2(40)  NOT NULL,
    ROLE_NAME         VARCHAR2(120) NOT NULL,
    DESCRIPTION       VARCHAR2(500),
    STATUS            VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_AV_ROLE PRIMARY KEY (ROLE_ID),
    CONSTRAINT FK_AV_ROLE_ORG FOREIGN KEY (ORGANIZATION_ID)
        REFERENCES AV_ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT UK_AV_ROLE_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_AV_ROLE_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE AV_PERMISSION (
    PERMISSION_ID    NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    PERMISSION_CODE  VARCHAR2(60)  NOT NULL,
    PERMISSION_NAME  VARCHAR2(120) NOT NULL,
    MODULE_CODE      VARCHAR2(40)  NOT NULL,
    ACTION_CODE      VARCHAR2(40)  NOT NULL,
    CONSTRAINT PK_AV_PERMISSION PRIMARY KEY (PERMISSION_ID),
    CONSTRAINT UK_AV_PERMISSION_CODE UNIQUE (PERMISSION_CODE)
);

CREATE TABLE AV_USER_ROLE (
    USER_ID  NUMBER(19) NOT NULL,
    ROLE_ID  NUMBER(19) NOT NULL,
    CONSTRAINT PK_AV_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID),
    CONSTRAINT FK_AV_USER_ROLE_USER FOREIGN KEY (USER_ID) REFERENCES AV_USER (USER_ID),
    CONSTRAINT FK_AV_USER_ROLE_ROLE FOREIGN KEY (ROLE_ID) REFERENCES AV_ROLE (ROLE_ID)
);

CREATE TABLE AV_ROLE_PERMISSION (
    ROLE_ID       NUMBER(19) NOT NULL,
    PERMISSION_ID NUMBER(19) NOT NULL,
    CONSTRAINT PK_AV_ROLE_PERMISSION PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_AV_ROLE_PERM_ROLE FOREIGN KEY (ROLE_ID) REFERENCES AV_ROLE (ROLE_ID),
    CONSTRAINT FK_AV_ROLE_PERM_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES AV_PERMISSION (PERMISSION_ID)
);

-- Essential for data isolation: backend verifies a user's assignment to a
-- business unit on every scoped request. Never inferred from the UI only.
CREATE TABLE AV_USER_BUSINESS_UNIT (
    USER_BUSINESS_UNIT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    USER_ID               NUMBER(19) NOT NULL,
    ORGANIZATION_ID       NUMBER(19) NOT NULL,
    BUSINESS_UNIT_ID      NUMBER(19) NOT NULL,
    ACCESS_LEVEL          VARCHAR2(20) NOT NULL,
    STATUS                VARCHAR2(20) NOT NULL,
    CREATED_AT            TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY            NUMBER(19),
    CONSTRAINT PK_AV_USER_BU PRIMARY KEY (USER_BUSINESS_UNIT_ID),
    CONSTRAINT FK_AV_USER_BU_USER FOREIGN KEY (USER_ID) REFERENCES AV_USER (USER_ID),
    CONSTRAINT FK_AV_USER_BU_SCOPE
        FOREIGN KEY (ORGANIZATION_ID, BUSINESS_UNIT_ID)
        REFERENCES AV_BUSINESS_UNIT (ORGANIZATION_ID, BUSINESS_UNIT_ID),
    CONSTRAINT UK_AV_USER_BU UNIQUE (USER_ID, BUSINESS_UNIT_ID),
    CONSTRAINT CK_AV_USER_BU_LEVEL CHECK (ACCESS_LEVEL IN ('FULL','VIEW')),
    CONSTRAINT CK_AV_USER_BU_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

-- Indexes on security FKs
CREATE INDEX IX_AV_USER_ORG        ON AV_USER (ORGANIZATION_ID);
CREATE INDEX IX_AV_USER_ROLE_USER  ON AV_USER_ROLE (USER_ID);
CREATE INDEX IX_AV_USER_ROLE_ROLE  ON AV_USER_ROLE (ROLE_ID);
CREATE INDEX IX_AV_ROLE_PERM_ROLE  ON AV_ROLE_PERMISSION (ROLE_ID);
CREATE INDEX IX_AV_ROLE_PERM_PERM  ON AV_ROLE_PERMISSION (PERMISSION_ID);
CREATE INDEX IX_AV_USER_BU_USER    ON AV_USER_BUSINESS_UNIT (USER_ID);
CREATE INDEX IX_AV_USER_BU_SCOPE   ON AV_USER_BUSINESS_UNIT (ORGANIZATION_ID, BUSINESS_UNIT_ID);