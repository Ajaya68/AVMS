-- ============================================================
-- V002__business_units.sql
-- Direct children of AV_ORGANIZATION. Composite keys enable
-- cross-scope-safe references from all down-stream tables.
-- ============================================================

CREATE TABLE AV_BUSINESS_UNIT (
    BUSINESS_UNIT_ID       NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID        NUMBER(19)  NOT NULL,
    BUSINESS_UNIT_CODE     VARCHAR2(20)  NOT NULL,
    BUSINESS_UNIT_NAME     VARCHAR2(120) NOT NULL,
    BUSINESS_UNIT_TYPE     VARCHAR2(40)  NOT NULL,
    DESCRIPTION            VARCHAR2(500),
    STATUS                 VARCHAR2(20)  NOT NULL,
    START_DATE             DATE,
    END_DATE               DATE,
    CREATED_AT             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY             NUMBER(19),
    UPDATED_AT             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY             NUMBER(19),
    VERSION_NO             NUMBER(19)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AV_BUSINESS_UNIT PRIMARY KEY (BUSINESS_UNIT_ID),
    CONSTRAINT FK_AV_BUSINESS_UNIT_ORG
        FOREIGN KEY (ORGANIZATION_ID) REFERENCES AV_ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT UK_AV_BUSINESS_UNIT_ORG_CODE UNIQUE (ORGANIZATION_ID, BUSINESS_UNIT_CODE),
    CONSTRAINT UK_AV_BUSINESS_UNIT_ORG_ID  UNIQUE (ORGANIZATION_ID, BUSINESS_UNIT_ID),
    CONSTRAINT CK_AV_BUSINESS_UNIT_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED')),
    CONSTRAINT CK_AV_BUSINESS_UNIT_END CHECK (END_DATE IS NULL OR END_DATE >= START_DATE)
);

-- Required composite-FK target index; also serves BU-per-org lookups.
CREATE INDEX IX_AV_BUSINESS_UNIT_ORG ON AV_BUSINESS_UNIT (ORGANIZATION_ID);