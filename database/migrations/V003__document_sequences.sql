-- ============================================================
-- V003__document_sequences.sql
-- Controlled business-document numbering. Never MAX+1; allocation
-- is transactional (see AV_DOCUMENT_NO_PKG added in a later
-- migration when document generation is exercised).
-- ============================================================

CREATE TABLE AV_DOCUMENT_SEQUENCE (
    DOCUMENT_SEQUENCE_ID  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID       NUMBER(19) NOT NULL,
    BUSINESS_UNIT_ID      NUMBER(19),
    DOCUMENT_TYPE         VARCHAR2(40)  NOT NULL,
    PREFIX                VARCHAR2(20),
    CURRENT_VALUE         NUMBER(19)    DEFAULT 0 NOT NULL,
    RESET_POLICY          VARCHAR2(20)  DEFAULT 'NONE' NOT NULL,
    YEAR_VALUE            NUMBER(4),
    STATUS                VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT PK_AV_DOCUMENT_SEQUENCE PRIMARY KEY (DOCUMENT_SEQUENCE_ID),
    CONSTRAINT FK_AV_DOC_SEQ_ORG
        FOREIGN KEY (ORGANIZATION_ID) REFERENCES AV_ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT FK_AV_DOC_SEQ_BU
        FOREIGN KEY (ORGANIZATION_ID, BUSINESS_UNIT_ID)
        REFERENCES AV_BUSINESS_UNIT (ORGANIZATION_ID, BUSINESS_UNIT_ID),
    CONSTRAINT CK_AV_DOC_SEQ_POLICY CHECK (RESET_POLICY IN ('NONE','YEARLY')),
    CONSTRAINT CK_AV_DOC_SEQ_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE UNIQUE INDEX UIX_AV_DOC_SEQ_SCOPE
    ON AV_DOCUMENT_SEQUENCE (ORGANIZATION_ID, DOCUMENT_TYPE, YEAR_VALUE,
                             NVL(BUSINESS_UNIT_ID, 0), RESET_POLICY);