CREATE TABLE AV_ORGANIZATION (
    ORGANIZATION_ID        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_CODE      VARCHAR2(20)  NOT NULL,
    ORGANIZATION_NAME      VARCHAR2(120) NOT NULL,
    LEGAL_NAME             VARCHAR2(200),
    DESCRIPTION            VARCHAR2(500),
    TAX_IDENTIFIER         VARCHAR2(40),
    EMAIL                  VARCHAR2(120),
    PHONE                  VARCHAR2(30),
    WEBSITE                VARCHAR2(120),
    ADDRESS_LINE_1         VARCHAR2(200),
    ADDRESS_LINE_2         VARCHAR2(200),
    CITY                   VARCHAR2(80),
    STATE_REGION           VARCHAR2(80),
    COUNTRY                VARCHAR2(60),
    POSTAL_CODE            VARCHAR2(20),
    DEFAULT_CURRENCY_CODE  VARCHAR2(3)   NOT NULL,
    DEFAULT_TIME_ZONE      VARCHAR2(40)  NOT NULL,
    STATUS                 VARCHAR2(20)  NOT NULL,
    CREATED_AT             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CREATED_BY             NUMBER(19),
    UPDATED_AT             TIMESTAMP(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_BY             NUMBER(19),
    VERSION_NO             NUMBER(19)    DEFAULT 0 NOT NULL,
    CONSTRAINT PK_AV_ORGANIZATION PRIMARY KEY (ORGANIZATION_ID),
    CONSTRAINT UK_AV_ORGANIZATION_CODE UNIQUE (ORGANIZATION_CODE),
    CONSTRAINT CK_AV_ORGANIZATION_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE','SUSPENDED'))
);