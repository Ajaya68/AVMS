-- ============================================================
-- V005__audit.sql
-- Immutable business audit trail. Ordinary business users cannot
-- UPDATE or DELETE. Passwords, tokens and secrets are never logged.
-- ============================================================

CREATE TABLE AV_AUDIT_EVENT (
    AUDIT_EVENT_ID   NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    ORGANIZATION_ID  NUMBER(19),
    BUSINESS_UNIT_ID NUMBER(19),
    USER_ID          NUMBER(19),
    REQUEST_ID       VARCHAR2(64),
    EVENT_TIME       TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ACTION_CODE      VARCHAR2(60)  NOT NULL,
    ENTITY_TYPE      VARCHAR2(60)  NOT NULL,
    ENTITY_ID        VARCHAR2(40),
    OUTCOME          VARCHAR2(20)  NOT NULL,
    IP_ADDRESS       VARCHAR2(45),
    USER_AGENT       VARCHAR2(255),
    BEFORE_SUMMARY   VARCHAR2(2000),
    AFTER_SUMMARY    VARCHAR2(2000),
    CONSTRAINT PK_AV_AUDIT_EVENT PRIMARY KEY (AUDIT_EVENT_ID),
    CONSTRAINT FK_AV_AUDIT_ORG FOREIGN KEY (ORGANIZATION_ID)
        REFERENCES AV_ORGANIZATION (ORGANIZATION_ID),
    CONSTRAINT FK_AV_AUDIT_SCOPE
        FOREIGN KEY (ORGANIZATION_ID, BUSINESS_UNIT_ID)
        REFERENCES AV_BUSINESS_UNIT (ORGANIZATION_ID, BUSINESS_UNIT_ID),
    CONSTRAINT FK_AV_AUDIT_USER FOREIGN KEY (USER_ID) REFERENCES AV_USER (USER_ID),
    CONSTRAINT CK_AV_AUDIT_OUTCOME CHECK (OUTCOME IN ('SUCCESS','FAILURE'))
);

-- Heavy write path: index by time and org for scanning/export.
CREATE INDEX IX_AV_AUDIT_ORG_TIME ON AV_AUDIT_EVENT (ORGANIZATION_ID, EVENT_TIME);
CREATE INDEX IX_AV_AUDIT_ENTITY   ON AV_AUDIT_EVENT (ENTITY_TYPE, ENTITY_ID);