-- V8: single-use password-reset tokens (V9+ must not rename this table).
-- Only SHA-256(token) is stored; the raw token travels in the reset link.

CREATE TABLE PASSWORD_RESET_TOKEN (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_email VARCHAR2(254) NOT NULL,
  token_hash VARCHAR2(64) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_prt_user ON PASSWORD_RESET_TOKEN (user_email);
CREATE INDEX idx_prt_expires ON PASSWORD_RESET_TOKEN (expires_at);
