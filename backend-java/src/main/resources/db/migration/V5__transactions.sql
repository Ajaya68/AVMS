-- V5 transactions wave: sales + purchases bills with nested items and returns.
-- Mirrors Django sales/purchases apps; totals maintained by SaleService/PurchaseService.

CREATE TABLE SALES_SALE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  customer_id NUMBER(19) NOT NULL REFERENCES CUSTOMERS_CUSTOMER(id),
  warehouse_id NUMBER(19) REFERENCES INVENTORY_WAREHOUSE(id) ON DELETE SET NULL,
  invoice_number VARCHAR2(20) NOT NULL,
  sale_date DATE NOT NULL,
  status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
  subtotal NUMBER(14,2) DEFAULT 0 NOT NULL,
  discount NUMBER(14,2) DEFAULT 0 NOT NULL,
  tax NUMBER(14,2) DEFAULT 0 NOT NULL,
  total_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  paid_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  returned_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  due_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  notes VARCHAR2(255),
  created_by NUMBER(19) REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_sale_venture_invoice UNIQUE (venture_id, invoice_number),
  CONSTRAINT chk_sale_status CHECK (status IN ('PENDING','PARTIAL','COMPLETED','RETURNED','CANCELLED'))
);
CREATE INDEX idx_sale_venture ON SALES_SALE (venture_id);
CREATE INDEX idx_sale_customer ON SALES_SALE (customer_id);

CREATE TABLE SALES_SALEITEM (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  sale_id NUMBER(19) NOT NULL REFERENCES SALES_SALE(id) ON DELETE CASCADE,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id),
  quantity NUMBER(14,2) NOT NULL,
  unit_price NUMBER(14,2) NOT NULL,
  discount NUMBER(14,2) DEFAULT 0 NOT NULL,
  tax NUMBER(14,2) DEFAULT 0 NOT NULL,
  total NUMBER(14,2) DEFAULT 0 NOT NULL
);
CREATE INDEX idx_saleitem_sale ON SALES_SALEITEM (sale_id);

CREATE TABLE SALES_SALERETURN (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  sale_id NUMBER(19) NOT NULL REFERENCES SALES_SALE(id),
  return_number VARCHAR2(20) NOT NULL,
  return_date DATE NOT NULL,
  status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
  total_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  notes VARCHAR2(255),
  created_by NUMBER(19) REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_salereturn_venture_number UNIQUE (venture_id, return_number),
  CONSTRAINT chk_salereturn_status CHECK (status IN ('PENDING','COMPLETED'))
);
CREATE INDEX idx_salereturn_venture ON SALES_SALERETURN (venture_id);

CREATE TABLE SALES_SALERETURNITEM (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  sale_return_id NUMBER(19) NOT NULL REFERENCES SALES_SALERETURN(id) ON DELETE CASCADE,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id),
  quantity NUMBER(14,2) NOT NULL,
  unit_price NUMBER(14,2) NOT NULL,
  total NUMBER(14,2) DEFAULT 0 NOT NULL
);
CREATE INDEX idx_salereturnitem_return ON SALES_SALERETURNITEM (sale_return_id);

CREATE TABLE PURCHASES_PURCHASE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  supplier_id NUMBER(19) NOT NULL REFERENCES SUPPLIERS_SUPPLIER(id),
  warehouse_id NUMBER(19) REFERENCES INVENTORY_WAREHOUSE(id) ON DELETE SET NULL,
  invoice_number VARCHAR2(20) NOT NULL,
  purchase_date DATE NOT NULL,
  status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
  subtotal NUMBER(14,2) DEFAULT 0 NOT NULL,
  discount NUMBER(14,2) DEFAULT 0 NOT NULL,
  tax NUMBER(14,2) DEFAULT 0 NOT NULL,
  total_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  paid_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  returned_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  due_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  notes VARCHAR2(255),
  created_by NUMBER(19) REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_purchase_venture_invoice UNIQUE (venture_id, invoice_number),
  CONSTRAINT chk_purchase_status CHECK (status IN ('PENDING','PARTIAL','COMPLETED','RETURNED','CANCELLED'))
);
CREATE INDEX idx_purchase_venture ON PURCHASES_PURCHASE (venture_id);
CREATE INDEX idx_purchase_supplier ON PURCHASES_PURCHASE (supplier_id);

CREATE TABLE PURCHASES_PURCHASEITEM (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  purchase_id NUMBER(19) NOT NULL REFERENCES PURCHASES_PURCHASE(id) ON DELETE CASCADE,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id),
  quantity NUMBER(14,2) NOT NULL,
  unit_price NUMBER(14,2) NOT NULL,
  discount NUMBER(14,2) DEFAULT 0 NOT NULL,
  tax NUMBER(14,2) DEFAULT 0 NOT NULL,
  total NUMBER(14,2) DEFAULT 0 NOT NULL
);
CREATE INDEX idx_purchaseitem_purchase ON PURCHASES_PURCHASEITEM (purchase_id);

CREATE TABLE PURCHASES_PURCHASERETURN (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  purchase_id NUMBER(19) NOT NULL REFERENCES PURCHASES_PURCHASE(id),
  return_number VARCHAR2(20) NOT NULL,
  return_date DATE NOT NULL,
  status VARCHAR2(20) DEFAULT 'COMPLETED' NOT NULL,
  total_amount NUMBER(14,2) DEFAULT 0 NOT NULL,
  notes VARCHAR2(255),
  created_by NUMBER(19) REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_purchasereturn_venture_number UNIQUE (venture_id, return_number),
  CONSTRAINT chk_purchasereturn_status CHECK (status IN ('PENDING','COMPLETED'))
);
CREATE INDEX idx_purchasereturn_venture ON PURCHASES_PURCHASERETURN (venture_id);

CREATE TABLE PURCHASES_PURCHASERETURNITEM (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  purchase_return_id NUMBER(19) NOT NULL REFERENCES PURCHASES_PURCHASERETURN(id) ON DELETE CASCADE,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id),
  quantity NUMBER(14,2) NOT NULL,
  unit_price NUMBER(14,2) NOT NULL,
  total NUMBER(14,2) DEFAULT 0 NOT NULL
);
CREATE INDEX idx_purchasereturnitem_return ON PURCHASES_PURCHASERETURNITEM (purchase_return_id);
