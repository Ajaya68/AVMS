-- V4 inventory wave: warehouses, stock rows, stock movements.
-- Mirrors Django inventory app; movement application via InventoryService.

CREATE TABLE INVENTORY_WAREHOUSE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  warehouse_code VARCHAR2(20) NOT NULL,
  warehouse_name VARCHAR2(150) NOT NULL,
  address VARCHAR2(255),
  city VARCHAR2(100),
  state VARCHAR2(100),
  pincode VARCHAR2(20),
  manager VARCHAR2(150),
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_warehouse_venture_code UNIQUE (venture_id, warehouse_code),
  CONSTRAINT chk_warehouse_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_warehouse_venture ON INVENTORY_WAREHOUSE (venture_id);

CREATE TABLE INVENTORY_STOCK (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  warehouse_id NUMBER(19) NOT NULL REFERENCES INVENTORY_WAREHOUSE(id) ON DELETE CASCADE,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id) ON DELETE CASCADE,
  quantity NUMBER(14,2) DEFAULT 0 NOT NULL,
  reserved_quantity NUMBER(14,2) DEFAULT 0 NOT NULL,
  reorder_level NUMBER(14,2) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_stock_warehouse_product UNIQUE (warehouse_id, product_id)
);
CREATE INDEX idx_stock_venture ON INVENTORY_STOCK (venture_id);
CREATE INDEX idx_stock_warehouse ON INVENTORY_STOCK (warehouse_id);

CREATE TABLE INVENTORY_MOVEMENT (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  warehouse_id NUMBER(19) NOT NULL REFERENCES INVENTORY_WAREHOUSE(id) ON DELETE CASCADE,
  destination_warehouse_id NUMBER(19) REFERENCES INVENTORY_WAREHOUSE(id) ON DELETE SET NULL,
  product_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_PRODUCT(id) ON DELETE CASCADE,
  movement_type VARCHAR2(20) NOT NULL,
  quantity NUMBER(14,2) NOT NULL,
  movement_date DATE NOT NULL,
  notes VARCHAR2(255),
  reference_type VARCHAR2(80),
  reference_id NUMBER(19),
  created_by NUMBER(19) REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  paired_movement_id NUMBER(19) REFERENCES INVENTORY_MOVEMENT(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_movement_type CHECK (movement_type IN ('PURCHASE','SALE','PURCHASE_RETURN',
    'SALES_RETURN','ADJUSTMENT_IN','ADJUSTMENT_OUT','TRANSFER_IN','TRANSFER_OUT'))
);
CREATE INDEX idx_movement_venture ON INVENTORY_MOVEMENT (venture_id);
CREATE INDEX idx_movement_warehouse ON INVENTORY_MOVEMENT (warehouse_id);
CREATE INDEX idx_movement_product ON INVENTORY_MOVEMENT (product_id);
