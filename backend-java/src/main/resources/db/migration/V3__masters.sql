-- V3 masters wave: customers, suppliers, units, categories, products.
-- Mirrors Django customers/suppliers/products apps; codes via CORE_SEQUENCE_COUNTER.

CREATE TABLE CUSTOMERS_CUSTOMER (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  customer_code VARCHAR2(20) NOT NULL,
  name VARCHAR2(150) NOT NULL,
  phone VARCHAR2(30),
  email VARCHAR2(254),
  address VARCHAR2(255),
  city VARCHAR2(100),
  state VARCHAR2(100),
  pincode VARCHAR2(20),
  gst_number VARCHAR2(30),
  credit_limit NUMBER(12,2) DEFAULT 0 NOT NULL,
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_customer_venture_code UNIQUE (venture_id, customer_code),
  CONSTRAINT chk_customer_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_customer_venture ON CUSTOMERS_CUSTOMER (venture_id);
CREATE INDEX idx_customer_name ON CUSTOMERS_CUSTOMER (name);

CREATE TABLE SUPPLIERS_SUPPLIER (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  supplier_code VARCHAR2(20) NOT NULL,
  name VARCHAR2(150) NOT NULL,
  contact_person VARCHAR2(150),
  phone VARCHAR2(30),
  email VARCHAR2(254),
  address VARCHAR2(255),
  city VARCHAR2(100),
  state VARCHAR2(100),
  pincode VARCHAR2(20),
  gst_number VARCHAR2(30),
  payment_terms VARCHAR2(100),
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_supplier_venture_code UNIQUE (venture_id, supplier_code),
  CONSTRAINT chk_supplier_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_supplier_venture ON SUPPLIERS_SUPPLIER (venture_id);
CREATE INDEX idx_supplier_name ON SUPPLIERS_SUPPLIER (name);

CREATE TABLE PRODUCTS_UNIT (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  unit_code VARCHAR2(20) NOT NULL UNIQUE,
  unit_name VARCHAR2(50) NOT NULL,
  is_base NUMBER(1) DEFAULT 1 NOT NULL
);

CREATE TABLE PRODUCTS_CATEGORY (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  category_name VARCHAR2(100) NOT NULL,
  description VARCHAR2(500),
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_category_venture_name UNIQUE (venture_id, category_name),
  CONSTRAINT chk_category_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_category_venture ON PRODUCTS_CATEGORY (venture_id);

CREATE TABLE PRODUCTS_PRODUCT (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  category_id NUMBER(19) REFERENCES PRODUCTS_CATEGORY(id) ON DELETE SET NULL,
  unit_id NUMBER(19) NOT NULL REFERENCES PRODUCTS_UNIT(id),
  sku VARCHAR2(20) NOT NULL,
  product_name VARCHAR2(150) NOT NULL,
  description VARCHAR2(1000),
  purchase_price NUMBER(12,2) DEFAULT 0 NOT NULL,
  selling_price NUMBER(12,2) DEFAULT 0 NOT NULL,
  tax_rate NUMBER(5,2) DEFAULT 0 NOT NULL,
  reorder_level NUMBER(12,2) DEFAULT 0 NOT NULL,
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_product_venture_sku UNIQUE (venture_id, sku),
  CONSTRAINT chk_product_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_product_venture ON PRODUCTS_PRODUCT (venture_id);
CREATE INDEX idx_product_name ON PRODUCTS_PRODUCT (product_name);
