-- V7 HR wave: employees + attendance.
-- Mirrors Django employees app; EMP-#### codes via CORE_SEQUENCE_COUNTER.

CREATE TABLE EMPLOYEES_EMPLOYEE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_id NUMBER(19) NOT NULL REFERENCES VENTURES_VENTURE(id) ON DELETE CASCADE,
  employee_code VARCHAR2(20) NOT NULL,
  first_name VARCHAR2(100) NOT NULL,
  last_name VARCHAR2(100),
  phone VARCHAR2(20),
  email VARCHAR2(254),
  department VARCHAR2(100),
  designation VARCHAR2(100),
  joining_date DATE,
  salary NUMBER(12,2) DEFAULT 0 NOT NULL,
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  user_id NUMBER(19) UNIQUE REFERENCES ACCOUNTS_USER(id) ON DELETE SET NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_employee_venture_code UNIQUE (venture_id, employee_code),
  CONSTRAINT chk_employee_status CHECK (status IN ('ACTIVE','INACTIVE','TERMINATED'))
);
CREATE INDEX idx_employee_venture ON EMPLOYEES_EMPLOYEE (venture_id);

CREATE TABLE EMPLOYEES_ATTENDANCE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  employee_id NUMBER(19) NOT NULL REFERENCES EMPLOYEES_EMPLOYEE(id) ON DELETE CASCADE,
  attendance_date DATE NOT NULL,
  status VARCHAR2(20) NOT NULL,
  check_in TIMESTAMP,
  check_out TIMESTAMP,
  notes VARCHAR2(255),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uniq_attendance_employee_date UNIQUE (employee_id, attendance_date),
  CONSTRAINT chk_attendance_status CHECK (status IN ('PRESENT','ABSENT','HALF_DAY','LEAVE'))
);
CREATE INDEX idx_attendance_employee ON EMPLOYEES_ATTENDANCE (employee_id);
CREATE INDEX idx_attendance_date ON EMPLOYEES_ATTENDANCE (attendance_date);
