-- AVMS Oracle baseline: foundation wave (accounts, ventures, sequence, audit, notifications, refresh tokens).
-- Later waves append V3+ migrations per module (customers, suppliers, products, inventory, ...).
-- Mirrors Django tables; PKs use Oracle IDENTITY; enums as VARCHAR2 + CHECK.

CREATE TABLE CORE_SEQUENCE_COUNTER (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  module VARCHAR2(40) NOT NULL,
  venture_id NUMBER(19) NULL,
  next_value NUMBER(19) DEFAULT 1 NOT NULL,
  CONSTRAINT uniq_sequence_module_venture UNIQUE (module, venture_id)
);

CREATE TABLE ACCOUNTS_PERMISSION (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  code VARCHAR2(80) NOT NULL UNIQUE,
  name VARCHAR2(120) NOT NULL,
  module VARCHAR2(60) NOT NULL
);
CREATE INDEX idx_permission_module ON ACCOUNTS_PERMISSION (module);

CREATE TABLE ACCOUNTS_ROLE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  code VARCHAR2(40) NOT NULL UNIQUE,
  name VARCHAR2(120) NOT NULL,
  description VARCHAR2(500),
  is_active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ACCOUNTS_ROLE_PERMISSIONS (
  role_id NUMBER(19) NOT NULL REFERENCES ACCOUNTS_ROLE(id) ON DELETE CASCADE,
  permission_id NUMBER(19) NOT NULL REFERENCES ACCOUNTS_PERMISSION(id) ON DELETE CASCADE,
  CONSTRAINT pk_role_perm PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE ACCOUNTS_USER (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  email VARCHAR2(254) NOT NULL UNIQUE,
  password VARCHAR2(255) NOT NULL,
  full_name VARCHAR2(150),
  phone VARCHAR2(30),
  is_active NUMBER(1) DEFAULT 1 NOT NULL,
  is_staff NUMBER(1) DEFAULT 0 NOT NULL,
  is_superuser NUMBER(1) DEFAULT 0 NOT NULL,
  last_login TIMESTAMP NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE ACCOUNTS_USER_ROLES (
  user_id NUMBER(19) NOT NULL REFERENCES ACCOUNTS_USER(id) ON DELETE CASCADE,
  role_id NUMBER(19) NOT NULL REFERENCES ACCOUNTS_ROLE(id) ON DELETE CASCADE,
  CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id)
);

CREATE TABLE REFRESH_TOKEN (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  jti VARCHAR2(64) NOT NULL UNIQUE,
  user_email VARCHAR2(254) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  revoked NUMBER(1) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE VENTURES_VENTURE (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  venture_code VARCHAR2(20) NOT NULL UNIQUE,
  venture_name VARCHAR2(150) NOT NULL,
  description VARCHAR2(1000),
  business_type VARCHAR2(30),
  phone VARCHAR2(30),
  email VARCHAR2(254),
  address VARCHAR2(255),
  city VARCHAR2(100),
  state VARCHAR2(100),
  pincode VARCHAR2(20),
  status VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_venture_status CHECK (status IN ('ACTIVE','INACTIVE'))
);
CREATE INDEX idx_venture_status ON VENTURES_VENTURE (status);

CREATE TABLE AUDIT_AUDITLOG (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_email VARCHAR2(254),
  action VARCHAR2(40) NOT NULL,
  module VARCHAR2(60) NOT NULL,
  object_type VARCHAR2(80),
  object_id VARCHAR2(80),
  ip_address VARCHAR2(45),
  description VARCHAR2(1000),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX idx_audit_module ON AUDIT_AUDITLOG (module);
CREATE INDEX idx_audit_created ON AUDIT_AUDITLOG (created_at);

CREATE TABLE NOTIFICATIONS_NOTIFICATION (
  id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_email VARCHAR2(254) NOT NULL,
  type VARCHAR2(30) NOT NULL,
  message VARCHAR2(255) NOT NULL,
  link VARCHAR2(255),
  is_read NUMBER(1) DEFAULT 0 NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT chk_notification_type CHECK (type IN ('LOW_STOCK','SALE_CREATED','PURCHASE_CREATED','PAYMENT_RECEIVED','PAYMENT_PAID','SYSTEM'))
);
CREATE INDEX idx_notification_user ON NOTIFICATIONS_NOTIFICATION (user_email, is_read, created_at);
